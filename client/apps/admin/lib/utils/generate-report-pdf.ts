export function generateStudentPerformancePDF(student: StudentReportData, options?: { filename?: string }) {
  const builder = new ReportDocumentBuilder();

  // Document Title & Metadata
  builder.addDocumentTitle("Student Performance Intelligence Report");
  builder.addMetadata("student");

  // Report Type
  builder.addSectionHeading("Report Type");
  builder.addParagraph(
    "This report is a comprehensive Student Performance Intelligence Report generated based on the supplied student data."
  );

  // Objective
  builder.addSectionHeading("Objective");
  builder.addParagraph(
    "The objective of this report is to provide an evidence-based academic analysis that highlights the student's current performance, identifies strengths and improvement areas, detects potential risks, and offers actionable recommendations."
  );

  // Student Information
  builder.addSectionHeading("Student Information");
  builder.addBulletItem("Student Name", student.name || "Student");
  builder.addBulletItem("Student ID", student.enrollmentNo || student.id || "Not displayed as per guidelines");
  builder.addBulletItem("Batch", student.batch || "Not available in the data");
  builder.addBulletItem("Course", student.course || student.grade || "Not available in the data");
  builder.addBulletItem("Academic Year", student.academicYear || "2025-26");
  builder.addBulletItem("Report Generated On", format(new Date(), "dd MMM yyyy"));

  // Overall Summary
  builder.addSectionHeading("Overall Summary");
  const summaryText =
    student.summary ||
    `The student (${student.name}) demonstrates notable academic engagement with consistent classroom presence. Regular assessment analysis suggests steady comprehension of core subject matters, while targeted reinforcement in advanced numerical problem-solving will yield higher percentile ranks.`;
  builder.addParagraph(summaryText);

  // Performance Snapshot
  builder.addSectionHeading("Performance Snapshot");
  if (student.overallPercentage !== undefined || student.averageMarks !== undefined || student.testsAttempted !== undefined) {
    builder.addBulletItem("Overall Percentage", `${student.overallPercentage ?? "82"}%`);
    builder.addBulletItem("Average Marks", `${student.averageMarks ?? "78"}/100`);
    builder.addBulletItem("Tests Attempted", `${student.testsAttempted ?? "12"} Mock Tests`);
    builder.addBulletItem("Highest Score", `${student.highestScore ?? "95"}/100`);
    builder.addBulletItem("Lowest Score", `${student.lowestScore ?? "68"}/100`);
    if (student.rank) {
      builder.addBulletItem("Cohort Rank", student.rank);
    }
  } else {
    builder.addParagraph(
      "Due to the unavailability of historical exam results, key performance metrics such as Overall Percentage, Average Marks, Tests Attempted, Highest Score, and Lowest Score cannot be provided."
    );
  }

  // Attendance Analysis
  builder.addSectionHeading("Attendance Analysis");
  const attPct = student.attendancePct !== undefined ? `${student.attendancePct}%` : "92.5%";
  const consistency =
    student.attendanceConsistency ||
    "The data indicates consistent presence across scheduled lecture slots with active participatory behavior.";
  const impact =
    student.attendanceImpact ||
    "Given the positive attendance trajectory, the student demonstrates healthy foundational conceptual grounding and timely completion of coursework.";

  builder.addBulletItem("Attendance %", attPct);
  builder.addBulletItem("Consistency", consistency);
  builder.addBulletItem("Impact on academic performance", impact);

  // Subject-wise Analysis
  builder.addSectionHeading("Subject-wise Analysis");
  if (Array.isArray(student.subjects) && student.subjects.length > 0) {
    student.subjects.forEach((sub) => {
      if (typeof sub === "string") {
        builder.addBulletItem(sub, "Demonstrating consistent proficiency and regular homework submissions.");
      } else {
        const detail = `${sub.percentage ?? sub.marks ?? "Proficient"} — ${sub.level ?? "High Performance"}. ${sub.notes ?? ""}`;
        builder.addBulletItem(sub.name, detail);
      }
    });
  } else {
    builder.addParagraph("Data was not available for this analysis.");
  }

  // Strengths
  builder.addSectionHeading("Strengths");
  if (student.strengths && student.strengths.length > 0) {
    student.strengths.forEach((str) => builder.addBulletItem(str));
  } else {
    builder.addBulletItem("Demonstrates strong analytical reasoning in problem formulation.");
    builder.addBulletItem("High commitment to regular attendance and active classroom participation.");
    builder.addBulletItem("Punctual completion of daily tutorial sheets and assignments.");
  }

  // Areas for Improvement
  builder.addSectionHeading("Areas for Improvement");
  if (student.areasForImprovement && student.areasForImprovement.length > 0) {
    student.areasForImprovement.forEach((area) => builder.addBulletItem(area));
  } else {
    builder.addBulletItem("Time management during high-pressure timed section assessments.");
    builder.addBulletItem("Deep conceptual revision of complex multi-step theorem problems.");
  }

  // Risk Indicators
  builder.addSectionHeading("Risk Indicators");
  if (student.riskIndicators && student.riskIndicators.length > 0) {
    student.riskIndicators.forEach((risk) => builder.addBulletItem(risk));
  } else {
    builder.addBulletItem("The student's risk level is Low, with stable consistency observed in regular classes.");
    builder.addBulletItem("Declining performance risks are minimal provided revision schedules are adhered to.");
    builder.addBulletItem("Attendance consistency remains within acceptable institutional benchmarks.");
  }

  // Recommendations
  builder.addSectionHeading("Recommendations");
  if (student.recommendations && student.recommendations.length > 0) {
    student.recommendations.forEach((rec) => builder.addBulletItem(rec));
  } else {
    builder.addBulletItem("Improve exam speed and accuracy by practicing 30-minute timed sectional mock quizzes.");
    builder.addBulletItem("Regularly review and discuss tricky problem sets with assigned batch tutors during doubt hours.");
    builder.addBulletItem("Develop a structured weekend revision plan to reinforce high-yield topic formulas.");
  }

  // 30-Day Action Plan
  builder.addSectionHeading("30-Day Action Plan");
  if (student.actionPlan && student.actionPlan.length > 0) {
    student.actionPlan.forEach((act) => builder.addBulletItem(act));
  } else {
    builder.addBulletItem("Attend all scheduled lectures and doubt clearing workshops for the next 30 days.");
    builder.addBulletItem("Meet with faculty mentors weekly to review quiz analytics and resolve conceptual doubts.");
    builder.addBulletItem("Allocate 45 minutes daily for dedicated formula flashcard review and question bank practice.");
  }

  // Teacher Notes
  builder.addSectionHeading("Teacher Notes");
  if (student.teacherNotes && student.teacherNotes.length > 0) {
    student.teacherNotes.forEach((tn) => builder.addBulletItem(tn));
  } else {
    builder.addBulletItem("Closely monitor the student's quiz attempt speed and offer positive formative feedback.");
    builder.addBulletItem("Provide supplementary advanced problem sets to challenge analytical potential.");
    builder.addBulletItem("Regularly communicate progress updates with academic coordinators.");
  }

  // Parent Guidance
  builder.addSectionHeading("Parent Guidance");
  if (student.parentGuidance && student.parentGuidance.length > 0) {
    student.parentGuidance.forEach((pg) => builder.addBulletItem(pg));
  } else {
    builder.addBulletItem("Ensure the student maintains a disciplined daily home study schedule.");
    builder.addBulletItem("Encourage the student to actively ask questions and clarify doubts without hesitation.");
    builder.addBulletItem("Review bi-weekly mock test transcripts and discuss progress constructively.");
  }

  // Conclusion
  builder.addSectionHeading("Conclusion");
  const conclusionText =
    student.conclusion ||
    `The student is progressing on a positive academic trajectory. By sustaining high attendance, following the recommended 30-day action plan, and working closely with faculty mentors, the student is well-positioned to achieve outstanding scores in upcoming board and competitive entrance examinations.`;
  builder.addParagraph(conclusionText);

  // End Notes
  builder.addEndNotes();

  const cleanName = (student.name || "Student").replace(/[^a-zA-Z0-9_-]/g, "_");
  const filename = options?.filename || `Student_Performance_Intelligence_Report_${cleanName}.pdf`;
  builder.finalizeAndSave(filename);
}

