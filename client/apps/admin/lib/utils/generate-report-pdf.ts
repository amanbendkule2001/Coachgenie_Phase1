/**
 * Base PDF Document builder with automated header/footer on each page,
 * consistent typography, divider lines, and page-break management.
 */
class ReportDocumentBuilder {
  doc: jsPDF;
  pageWidth: number;
  pageHeight: number;
  marginLeft: number = 18;
  marginRight: number = 18;
  contentWidth: number;
  curY: number = 28;
  generatedDateStr: string;
  generatedTimestampStr: string;

  constructor() {
    this.doc = new jsPDF({
      orientation: "portrait",
      unit: "mm",
      format: "a4",
    });

    this.pageWidth = this.doc.internal.pageSize.getWidth();
    this.pageHeight = this.doc.internal.pageSize.getHeight();
    this.contentWidth = this.pageWidth - this.marginLeft - this.marginRight;

    const now = new Date();
    this.generatedDateStr = format(now, "dd MMM yyyy HH:mm");
    this.generatedTimestampStr = `${format(now, "yyyy-MM-dd HH:mm:ss")}.${String(now.getMilliseconds()).padStart(3, "0")}000`;
  }

  ensureSpace(neededHeightMm: number) {
    if (this.curY + neededHeightMm > this.pageHeight - 20) {
      this.doc.addPage();
      this.curY = 28;
    }
  }

  addDivider(extraSpacingBefore = 2, extraSpacingAfter = 4) {
    this.ensureSpace(extraSpacingBefore + extraSpacingAfter + 1);
    this.curY += extraSpacingBefore;
    this.doc.setDrawColor(209, 213, 219); // #D1D5DB
    this.doc.setLineWidth(0.35);
    this.doc.line(this.marginLeft, this.curY, this.pageWidth - this.marginRight, this.curY);
    this.curY += extraSpacingAfter;
  }

  addDocumentTitle(title: string) {
    this.ensureSpace(18);
    this.doc.setFont("helvetica", "bold");
    this.doc.setFontSize(20);
    this.doc.setTextColor(17, 24, 39); // #111827
    this.doc.text(title, this.pageWidth / 2, this.curY + 6, { align: "center" });
    this.curY += 14;
  }

  addMetadata(reportType: string) {
    this.addDivider(2, 4);

    this.ensureSpace(12);
    this.doc.setFont("helvetica", "bold");
    this.doc.setFontSize(9.5);
    this.doc.setTextColor(17, 24, 39);
    this.doc.text(`Generated On: ${this.generatedTimestampStr}  Generated By: Coach Genie AI`, this.marginLeft, this.curY);
    this.curY += 6;

    this.doc.text(`Report Type: ${reportType}`, this.marginLeft, this.curY);
    this.curY += 6;
  }

  addSectionHeading(title: string) {
    this.ensureSpace(14);
    this.curY += 4;
    this.doc.setFont("helvetica", "bold");
    this.doc.setFontSize(14.5);
    this.doc.setTextColor(31, 41, 55); // #1F2937
    this.doc.text(title, this.marginLeft, this.curY);
    this.curY += 6.5;
  }

  addParagraph(text: string) {
    if (!text || !text.trim()) return;
    this.doc.setFont("helvetica", "normal");
    this.doc.setFontSize(10.5);
    this.doc.setTextColor(31, 41, 55);

    const lines = this.doc.splitTextToSize(text.trim(), this.contentWidth);
    for (const line of lines) {
      this.ensureSpace(5.5);
      this.doc.text(line, this.marginLeft, this.curY);
      this.curY += 5.2;
    }
    this.curY += 2;
  }

  addBulletItem(label: string, value?: string) {
    const bulletPrefix = "•  ";
    this.ensureSpace(6);

    this.doc.setFontSize(10.5);
    const bulletX = this.marginLeft;
    const textX = this.marginLeft + 5;
    const textWidth = this.contentWidth - 5;

    this.doc.setFont("helvetica", "bold");
    this.doc.setTextColor(31, 41, 55);
    this.doc.text(bulletPrefix, bulletX, this.curY);

    if (value !== undefined) {
      // Key-Value bullet like "• Student Name: Soniya"
      const fullText = `${label}: ${value}`;
      const lines = this.doc.splitTextToSize(fullText, textWidth);

      for (let i = 0; i < lines.length; i++) {
        if (i > 0) this.ensureSpace(5.2);
        
        if (i === 0) {
          // Render bold label first, then normal value if it fits
          this.doc.setFont("helvetica", "bold");
          const labelPart = `${label}: `;
          this.doc.text(labelPart, textX, this.curY);
          const labelPartWidth = this.doc.getTextWidth(labelPart);

          this.doc.setFont("helvetica", "normal");
          // Print remainder of line
          const firstLineRemainder = lines[0].slice(labelPart.length);
          if (firstLineRemainder) {
            this.doc.text(firstLineRemainder, textX + labelPartWidth, this.curY);
          }
        } else {
          this.doc.setFont("helvetica", "normal");
          this.doc.text(lines[i], textX, this.curY);
        }
        this.curY += 5.2;
      }
    } else {
      // Regular descriptive bullet point
      const lines = this.doc.splitTextToSize(label, textWidth);
      this.doc.setFont("helvetica", "normal");
      for (let i = 0; i < lines.length; i++) {
        if (i > 0) this.ensureSpace(5.2);
        this.doc.text(lines[i], textX, this.curY);
        this.curY += 5.2;
      }
    }
    this.curY += 1.5;
  }

  addEndNotes() {
    this.addDivider(4, 5);

    this.ensureSpace(12);
    this.doc.setFont("helvetica", "normal");
    this.doc.setFontSize(10);
    this.doc.setTextColor(31, 41, 55);
    this.doc.text("Generated by Coach Genie AI", this.marginLeft, this.curY);
    this.curY += 6;

    this.doc.setFont("helvetica", "italic");
    this.doc.text("End of Report", this.marginLeft, this.curY);
    this.curY += 6;
  }

  finalizeAndSave(filename: string) {
    const totalPages = this.doc.getNumberOfPages();

    for (let page = 1; page <= totalPages; page++) {
      this.doc.setPage(page);

      // Running Header
      this.doc.setFont("helvetica", "bold");
      this.doc.setFontSize(10.5);
      this.doc.setTextColor(17, 24, 39); // #111827
      this.doc.text("Coach Genie AI", this.marginLeft, 13);

      this.doc.setDrawColor(209, 213, 219); // #D1D5DB
      this.doc.setLineWidth(0.35);
      this.doc.line(this.marginLeft, 17, this.pageWidth - this.marginRight, 17);

      // Running Footer
      this.doc.setDrawColor(209, 213, 219);
      this.doc.setLineWidth(0.35);
      this.doc.line(this.marginLeft, this.pageHeight - 16, this.pageWidth - this.marginRight, this.pageHeight - 16);

      this.doc.setFont("helvetica", "normal");
      this.doc.setFontSize(9);
      this.doc.setTextColor(107, 114, 128); // #6B7280
      this.doc.text(`Generated on ${this.generatedDateStr}`, this.marginLeft, this.pageHeight - 10);
      this.doc.text(`Page ${page}`, this.pageWidth - this.marginRight, this.pageHeight - 10, { align: "right" });
    }

    const safeFilename = filename.endsWith(".pdf") ? filename : `${filename}.pdf`;
    this.doc.save(safeFilename);
  }
}

