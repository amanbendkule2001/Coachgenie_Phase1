// 3. ATTENDANCE INTELLIGENCE REPORT
// =========================================================================
export function generateAttendanceReportPDF(data: AttendanceReportData, options?: { filename?: string }) {
  const builder = new ReportDocumentBuilder();

  // Document Title & Metadata
  builder.addDocumentTitle("Attendance Intelligence Report");
  builder.addMetadata("attendance");

  // Report Type
  builder.addSectionHeading("Report Type");
  builder.addParagraph(
    "This report is an Attendance Intelligence Report generated based on institutional session records and roster logs."
  );

  // Objective
  builder.addSectionHeading("Objective");
  builder.addParagraph(
    "The objective of this report is to analyze student presence trends, detect absenteeism patterns, evaluate engagement health, and offer corrective measures."
  );

  // Attendance Information
  builder.addSectionHeading("Attendance Information");
  builder.addBulletItem("Selected Batch", data.batchName || "Standard Batch");
  builder.addBulletItem("Session Date", data.sessionDate ? format(new Date(data.sessionDate), "EEEE, dd MMMM yyyy") : format(new Date(), "EEEE, dd MMMM yyyy"));
  builder.addBulletItem("Total Enrolled Roster", `${data.totalStudents} Students`);
  const presentPct = data.totalStudents > 0 ? Math.round((data.presentCount / data.totalStudents) * 100) : 0;
  const absentPct = data.totalStudents > 0 ? Math.round((data.absentCount / data.totalStudents) * 100) : 0;

  builder.addBulletItem("Present Count", `${data.presentCount} (${presentPct}%)`);
  builder.addBulletItem("Absent Count", `${data.absentCount} (${absentPct}%)`);
  if (data.lateCount !== undefined && data.lateCount > 0) {
    builder.addBulletItem("Late / Excused Count", `${data.lateCount}`);
  }
  builder.addBulletItem("Report Generated On", format(new Date(), "dd MMM yyyy"));

  // Overall Summary
  builder.addSectionHeading("Overall Summary");
  const summaryText =
    data.summary ||
    `Attendance logging for batch "${data.batchName}" on ${data.sessionDate} recorded an overall presence rate of ${data.attendancePercentage || presentPct}%. The session was conducted with high student engagement, and absent students have been flagged for automated guardian notifications.`;
  builder.addParagraph(summaryText);

  // Attendance Analysis
  builder.addSectionHeading("Attendance Analysis");
  if (data.attendanceAnalysis && data.attendanceAnalysis.length > 0) {
    data.attendanceAnalysis.forEach((item) => builder.addBulletItem(item));
  } else {
    builder.addBulletItem("Attendance %", `${data.attendancePercentage || presentPct}%`);
    builder.addBulletItem(
      "Consistency",
      data.absentCount === 0
        ? "Perfect 100% full attendance recorded for this session."
        : `Overall cohort consistency is strong, with ${data.presentCount} out of ${data.totalStudents} students attending scheduled class lectures.`
    );
    builder.addBulletItem(
      "Impact on academic performance",
      "Regular presence directly correlates with mastery in modular weekly problem sets and conceptual tests."
    );
  }

  // Students Requiring Attention
  builder.addSectionHeading("Students Requiring Attention");
  const absentees = data.studentsList?.filter((s) => s.status === "ABSENT") ?? [];
  if (absentees.length > 0) {
    absentees.forEach((stu) => {
      builder.addBulletItem(stu.name, `Marked ABSENT on ${data.sessionDate}. Follow-up recommended.`);
    });
  } else {
    builder.addParagraph("No chronic absentees or concerning attendance anomalies detected for this session.");
  }

  // Risk Indicators
  builder.addSectionHeading("Risk Indicators");
  if (data.riskIndicators && data.riskIndicators.length > 0) {
    data.riskIndicators.forEach((r) => builder.addBulletItem(r));
  } else {
    builder.addBulletItem("Cohort attendance risk level is Low with stable active enrollment.");
    builder.addBulletItem("Unexcused absence rates remain well within institutional tolerance parameters.");
  }

  // Recommendations
  builder.addSectionHeading("Recommendations");
  if (data.recommendations && data.recommendations.length > 0) {
    data.recommendations.forEach((r) => builder.addBulletItem(r));
  } else {
    builder.addBulletItem("Send automated SMS/WhatsApp alerts to guardians of unexcused absent students.");
    builder.addBulletItem("Provide lecture notes and assignment sheets to students returning from excused absence.");
    builder.addBulletItem("Reward students maintaining 100% monthly attendance with academic merit commendations.");
  }

  // Teacher Notes
  builder.addSectionHeading("Teacher Notes");
  if (data.teacherNotes && data.teacherNotes.length > 0) {
    data.teacherNotes.forEach((tn) => builder.addBulletItem(tn));
  } else {
    builder.addBulletItem("Confirm student presence at the start of each class slot.");
    builder.addBulletItem("Brief absentees on missed syllabus topics during office doubt hours.");
  }

  // Parent Guidance
  builder.addSectionHeading("Parent Guidance");
  if (data.parentGuidance && data.parentGuidance.length > 0) {
    data.parentGuidance.forEach((pg) => builder.addBulletItem(pg));
  } else {
    builder.addBulletItem("Notify institute coordinators in advance if a student requires medical or family leave.");
    builder.addBulletItem("Ensure students review daily lecture notes if a class is unavoidably missed.");
  }

  // Conclusion
  builder.addSectionHeading("Conclusion");
  const conclusionText =
    data.conclusion ||
    `The attendance record for batch ${data.batchName} on ${data.sessionDate} reflects consistent discipline and engagement. Continued adherence to attendance protocols will maximize academic achievement.`;
  builder.addParagraph(conclusionText);

  // End Notes
  builder.addEndNotes();

  const cleanBatch = (data.batchName || "Batch").replace(/[^a-zA-Z0-9_-]/g, "_");
  const cleanDate = (data.sessionDate || "Session").replace(/[^a-zA-Z0-9_-]/g, "_");
  const filename = options?.filename || `Attendance_Intelligence_Report_${cleanBatch}_${cleanDate}.pdf`;
  builder.finalizeAndSave(filename);
}
